function [EEGclean, com, report] = pop_cleanline_gpt6(EEG, varargin)
%POP_CLEANLINE_GPT6 EEGLAB GUI and scriptable CleanLine V2 entry point.
% [EEG,com,report] = pop_cleanline_gpt6(EEG,'Implementation','optimized', ...
%     'ExecutionMode','serial','LineFrequencies',60,'ChanCompIndices',1:EEG.nbchan);
EEGclean=EEG;
com='';
report=struct();
if nargin<1 || isempty(EEG)
    help pop_cleanline_gpt6;
    return
end
if isempty(varargin)
    [defaults,accepted]=cleanline_gpt6_settings_dialog(EEG);
    if ~accepted, return; end
    varargin=[defaults,{'ShowProgress',true}];
end
[EEGclean,~,report]=cleanline_gpt6(EEG,varargin{:});
g=report.parameters;
com=['EEG = pop_cleanline_gpt6(EEG, ', ...
    '''Implementation'',''',report.implementation,''',', ...
    '''ExecutionMode'',''',report.executionMode,''',', ...
    '''LineFrequencies'',',mat2str(report.requestedLineFrequencies),',', ...
    '''ChanCompIndices'',',mat2str(report.channels),',', ...
    '''LineAlpha'',',num2str(g.LineAlpha,17),',', ...
    '''Bandwidth'',',num2str(g.Bandwidth,17),',', ...
    '''TaperBandWidth'',',num2str(g.TaperBandWidth,17),',', ...
    '''SlidingWinLength'',',num2str(g.SlidingWinLength,17),',', ...
    '''SlidingWinStep'',',num2str(g.SlidingWinStep,17),',', ...
    '''SmoothingFactor'',',num2str(g.SmoothingFactor,17),',', ...
    '''PaddingFactor'',',num2str(g.PaddingFactor,17),',', ...
    '''ShowProgress'',',mat2str(logical(g.ShowProgress)),',', ...
    '''Newversion'',1);'];
if ~isfield(EEGclean,'etc') || isempty(EEGclean.etc)
    EEGclean.etc=struct();
end
report.historyCommand=com;
report.originalEventCount=numel(EEG.event);
if isempty(EEG.event)
    report.boundaryEventCount=0;
else
    report.boundaryEventCount=nnz(strcmpi({EEG.event.type},'boundary'));
end
EEGclean.etc.cleanline_gpt6=report;
end
