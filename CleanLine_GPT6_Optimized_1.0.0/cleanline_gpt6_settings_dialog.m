function [args,accepted] = cleanline_gpt6_settings_dialog(EEG)
%CLEANLINE_GPT6_SETTINGS_DIALOG Single-window CleanLine V2 settings dialog.
% GUI design and color scheme match the BLASST Standalone settings dialog.
% The processing engine and numeric defaults are unchanged.
args = {};
accepted = false;
assert(isstruct(EEG) && isfield(EEG,'nbchan') && EEG.nbchan >= 1, ...
    'CleanLineGPT6:Dialog requires an EEGLAB dataset with channels.');

labels = { ...
    'Line frequencies (Hz; one frequency includes harmonics):', ...
    'Channel indices (e.g., 1:33; blank for all):', ...
    'F-test p-value:', ...
    'Scan bandwidth (Hz):', ...
    'Taper bandwidth (Hz):', ...
    'Sliding window length (seconds):', ...
    'Sliding window step (seconds):', ...
    'Overlap smoothing tau:', ...
    'FFT padding factor:'};
defaults = {'60',sprintf('1:%d',EEG.nbchan),'0.01','2','2', ...
    '4','1','100','2'};

% Reuse the established BLASST palette and single-screen dialog layout.
bg = [0.66 0.76 1];
labelFg = [0 0 0.4];
inputFg = [0 0 0];
buttonBg = [0.93 0.96 1];
screen = get(0,'ScreenSize');
sx = min(1,max(0.65,(screen(3)-60)/715));
sy = min(1,max(0.65,(screen(4)-90)/835));
width = round(715*sx);
height = round(835*sy);
left = max(1,round(screen(1)+(screen(3)-width)/2));
bottom = max(1,round(screen(2)+(screen(4)-height)/2));
pos = @(x,y,w,ht) round([x*sx y*sy w*sx ht*sy]);
fontSize = max(8,10*min(sx,sy));

h = dialog('Name','CleanLine GPT-6 Optimized v1.0.0', ...
    'Units','pixels','Position',[left bottom width height], ...
    'Resize','off','WindowStyle','modal','Color',bg, ...
    'Tag','CleanLineGPT6SettingsDialog', ...
    'CloseRequestFcn',@(src,~)delete(src));
edits = gobjects(1,9);
for k = 1:9
    y = 835 - 41 - (k-1)*55;
    uicontrol('Parent',h,'Style','text','String',labels{k}, ...
        'Units','pixels','Position',pos(20,y,675,22), ...
        'BackgroundColor',bg,'ForegroundColor',labelFg, ...
        'HorizontalAlignment','left','FontSize',fontSize);
    edits(k) = uicontrol('Parent',h,'Style','edit', ...
        'String',defaults{k},'Units','pixels', ...
        'Position',pos(20,y-35,675,30), ...
        'BackgroundColor','white','ForegroundColor',inputFg, ...
        'HorizontalAlignment','left','FontSize',fontSize, ...
        'Tag',sprintf('CleanLineSetting%d',k));
end

uicontrol('Parent',h,'Style','text','String','Execution mode:', ...
    'Units','pixels','Position',pos(20,285,675,22), ...
    'BackgroundColor',bg,'ForegroundColor',labelFg, ...
    'HorizontalAlignment','left','FontSize',fontSize);
modePopup = uicontrol('Parent',h,'Style','popupmenu', ...
    'String',{'Serial','Parallel (Parallel Computing Toolbox)'}, ...
    'Value',1,'Units','pixels','Position',pos(20,251,675,30), ...
    'BackgroundColor','white','ForegroundColor',inputFg, ...
    'HorizontalAlignment','left','FontSize',fontSize, ...
    'Tag','CleanLineExecutionMode');

uicontrol('Parent',h,'Style','text','String','CleanLine implementation:', ...
    'Units','pixels','Position',pos(20,211,675,22), ...
    'BackgroundColor',bg,'ForegroundColor',labelFg, ...
    'HorizontalAlignment','left','FontSize',fontSize);
implementationPopup = uicontrol('Parent',h,'Style','popupmenu', ...
    'String',{'Optimized CleanLine V2 (default)', ...
              'Original CleanLine V2 (Kay Robbins PREP rewrite)'}, ...
    'Value',1,'Units','pixels','Position',pos(20,177,675,30), ...
    'BackgroundColor','white','ForegroundColor',inputFg, ...
    'HorizontalAlignment','left','FontSize',fontSize, ...
    'Tag','CleanLineImplementation');

% Two static, non-editable references, in the same position as in BLASST.
uicontrol('Parent',h,'Style','text','String','Reference', ...
    'Units','pixels','Position',pos(20,129,675,21), ...
    'BackgroundColor',bg,'ForegroundColor',labelFg, ...
    'HorizontalAlignment','left','FontWeight','bold', ...
    'FontSize',fontSize,'Tag','CleanLineReferenceHeader');
uicontrol('Parent',h,'Style','text', ...
    'String','Mullen (2012), CleanLine, NITRC (RRID:SCR_002233). www.nitrc.org/projects/cleanline', ...
    'Units','pixels','Position',pos(20,105,675,20), ...
    'BackgroundColor',bg,'ForegroundColor',labelFg, ...
    'HorizontalAlignment','left','FontSize',fontSize, ...
    'Tag','CleanLineReferenceMullen');
uicontrol('Parent',h,'Style','text', ...
    'String','Bigdely-Shamlo et al. (2015), Front Neuroinform 9:16. DOI: 10.3389/fninf.2015.00016', ...
    'Units','pixels','Position',pos(20,81,675,20), ...
    'BackgroundColor',bg,'ForegroundColor',labelFg, ...
    'HorizontalAlignment','left','FontSize',fontSize, ...
    'Tag','CleanLineReferencePREP');

uicontrol('Parent',h,'Style','pushbutton','String','OK', ...
    'Units','pixels','Position',pos(530,16,78,35), ...
    'BackgroundColor',buttonBg,'ForegroundColor',labelFg, ...
    'FontSize',fontSize,'Tag','CleanLineOKButton', ...
    'Callback',@(~,~)uiresume(h));
uicontrol('Parent',h,'Style','pushbutton','String','Cancel', ...
    'Units','pixels','Position',pos(619,16,78,35), ...
    'BackgroundColor',buttonBg,'ForegroundColor',labelFg, ...
    'FontSize',fontSize,'Tag','CleanLineCancelButton', ...
    'Callback',@(~,~)delete(h));

setappdata(h,'CleanLineSettingsEdits',edits);
setappdata(h,'CleanLineExecutionModePopup',modePopup);
setappdata(h,'CleanLineImplementationPopup',implementationPopup);

% Invalid inputs leave the same dialog open for correction.
while isgraphics(h)
    uiwait(h);
    if ~isgraphics(h)
        return
    end
    answer = cell(1,9);
    for k = 1:9
        answer{k} = get(edits(k),'String');
    end
    try
        freqs = str2num(answer{1}); %#ok<ST2NM>
        if isempty(strtrim(answer{2}))
            channels = 1:EEG.nbchan;
        else
            channels = str2num(answer{2}); %#ok<ST2NM>
        end
    catch
        freqs = [];
        channels = [];
    end
    nums = cellfun(@str2double,answer(3:9));
    validFreqs = isnumeric(freqs) && isvector(freqs) && ...
        ~isempty(freqs) && all(isfinite(freqs)) && all(freqs > 0);
    validChannels = isnumeric(channels) && isvector(channels) && ...
        ~isempty(channels) && all(isfinite(channels)) && ...
        all(channels == fix(channels)) && ...
        all(channels >= 1 & channels <= EEG.nbchan);
    validNums = all(isfinite(nums)) && ...
        nums(1) > 0 && nums(1) < 1 && ...
        all(nums(2:4) > 0) && nums(5) > 0 && ...
        nums(5) <= nums(4) && nums(6) >= 1 && nums(7) >= -1;
    if ~(validFreqs && validChannels && validNums)
        errordlg(['Please check frequencies, channel indices (1 to ' ...
            num2str(EEG.nbchan) '), and numeric settings. ' ...
            'The F-test p-value must be between 0 and 1; ' ...
            'bandwidths/window lengths/steps must be positive; ' ...
            'the step cannot exceed the window length; ' ...
            'tau must be at least 1 and padding at least -1.'], ...
            'Invalid CleanLine setting','modal');
        continue
    end
    modes = {'serial','parallel'};
    implementations = {'optimized','original'};
    mode = modes{get(modePopup,'Value')};
    implementation = implementations{get(implementationPopup,'Value')};
    args = {'Implementation',implementation,'ExecutionMode',mode, ...
        'LineFrequencies',freqs,'ChanCompIndices',channels, ...
        'LineAlpha',nums(1),'Bandwidth',nums(2), ...
        'TaperBandWidth',nums(3),'SlidingWinLength',nums(4), ...
        'SlidingWinStep',nums(5),'SmoothingFactor',nums(6), ...
        'PaddingFactor',nums(7),'Newversion',1};
    accepted = true;
    delete(h);
    return
end
end
