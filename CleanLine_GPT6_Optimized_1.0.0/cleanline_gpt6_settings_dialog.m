function [args,accepted] = cleanline_gpt6_settings_dialog(EEG)
%CLEANLINE_GPT6_SETTINGS_DIALOG Interactive V2 settings.
args={};
accepted=false;
choices={'Optimized','Original'};
[selected,ok]=listdlg('ListString',choices,'SelectionMode','single', ...
    'InitialValue',1,'PromptString','CleanLine 2.00 implementation', ...
    'Name','CleanLine GPT-6 Optimized');
if ~ok, return; end
implementation=lower(choices{selected});
choices={'Serial','Parallel'};
[selected,ok]=listdlg('ListString',choices,'SelectionMode','single', ...
    'InitialValue',1,'PromptString','Execution mode', ...
    'Name','CleanLine GPT-6 Optimized');
if ~ok, return; end
mode=lower(choices{selected});
defaults={'60',sprintf('1:%d',EEG.nbchan),'0.01','2','2','4','1','100','2'};
labels={'Line frequency (Hz; one value automatically includes harmonics)', ...
    'Channel indices','F-test p value','Scan bandwidth (Hz)', ...
    'Taper bandwidth (Hz)','Window length (s)','Window step (s)', ...
    'Overlap smoothing tau','FFT padding factor'};
answer=inputdlg(labels,'CleanLine GPT-6 Optimized',1,defaults);
if isempty(answer), return; end
freqs=str2num(answer{1}); %#ok<ST2NM>
channels=str2num(answer{2}); %#ok<ST2NM>
nums=cellfun(@str2double,answer(3:end));
assert(~isempty(freqs) && ~isempty(channels) && all(isfinite(nums)), ...
    'Invalid numeric CleanLine setting.');
args={'Implementation',implementation,'ExecutionMode',mode, ...
    'LineFrequencies',freqs,'ChanCompIndices',channels, ...
    'LineAlpha',nums(1),'Bandwidth',nums(2), ...
    'TaperBandWidth',nums(3),'SlidingWinLength',nums(4), ...
    'SlidingWinStep',nums(5),'SmoothingFactor',nums(6), ...
    'PaddingFactor',nums(7),'Newversion',1};
accepted=true;
end
